<?php

namespace Folklore\Tests\Unit\Support;

use Folklore\Support\ShortUuid;
use PHPUnit\Framework\TestCase;
use Ramsey\Uuid\Uuid;

class ShortUuidTest extends TestCase
{
    public function test_encodes_a_known_uuid()
    {
        $shortUuid = new ShortUuid;

        $this->assertSame(
            'fpfyRTmt6XeE9ehEKZ5LwF',
            $shortUuid->encode(Uuid::fromString('4e52c919-513e-4562-9248-7dd612c6c1ca')),
        );
    }

    public function test_decodes_a_known_short_uuid()
    {
        $shortUuid = new ShortUuid;

        $this->assertSame(
            '4e52c919-513e-4562-9248-7dd612c6c1ca',
            $shortUuid->decode('fpfyRTmt6XeE9ehEKZ5LwF')->toString(),
        );
    }

    public function test_round_trip()
    {
        $shortUuid = new ShortUuid;
        $uuid = Uuid::uuid4();

        $this->assertTrue($uuid->equals($shortUuid->decode($shortUuid->encode($uuid))));
    }

    public function test_generates_short_uuids()
    {
        // 22 characters at most, fewer when the UUID's high bits are zero (#66)
        $this->assertMatchesRegularExpression('/^[2-9A-HJ-NP-Za-km-z]{1,22}$/', ShortUuid::uuid4());
        $this->assertSame(
            ShortUuid::uuid5(Uuid::NAMESPACE_URL, 'https://folklore.email'),
            ShortUuid::uuid5(Uuid::NAMESPACE_URL, 'https://folklore.email'),
        );
    }

    public function test_a_uuid_with_leading_zero_bits_gives_a_shorter_string_that_decodes_back()
    {
        $shortUuid = new ShortUuid;

        // The 20-character id generated by uuid4() when the test failed in CI (#66)
        $this->assertSame('000e4244-9cb3-4247-b4dd-6c74d8db0443', $shortUuid->decode('DRbpNNXj4Tafr37AfGDa')->toString());
        $this->assertSame('DRbpNNXj4Tafr37AfGDa', $shortUuid->encode(Uuid::fromString('000e4244-9cb3-4247-b4dd-6c74d8db0443')));

        foreach ([
            'ffffffff-ffff-4fff-bfff-ffffffffffff' => 22,
            '0000ffff-ffff-4fff-bfff-ffffffffffff' => 20,
            '00000000-0000-4000-8000-000000000000' => 14,
        ] as $uuid => $length) {
            $encoded = $shortUuid->encode(Uuid::fromString($uuid));

            $this->assertSame($length, strlen($encoded), $uuid);
            $this->assertSame($uuid, $shortUuid->decode($encoded)->toString());
        }
    }

    public function test_custom_alphabet()
    {
        $shortUuid = new ShortUuid(['0', '1']);
        $uuid = Uuid::uuid4();

        $this->assertSame(['0', '1'], $shortUuid->getAlphabet());
        $this->assertMatchesRegularExpression('/^[01]+$/', $shortUuid->encode($uuid));
        $this->assertTrue($uuid->equals($shortUuid->decode($shortUuid->encode($uuid))));
    }
}
